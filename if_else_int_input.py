# โปรแกรมเช็คผลสอบจำลอง
# int(input(...)): คำว่า input คือการรับข้อความที่เราพิมพ์ แต่เนื่องจากคอมพิวเตอร์มองเป็นตัวอักษร เราจึงใส่ int() ครอบไว้เพื่อแปลงให้มันกลายเป็น "ตัวเลขจำนวนเต็ม" จริงๆ จะได้เอาไปเปรียบเทียบมากกว่า/น้อยกว่าได้
score = int(input("กรอกคะแนนข้อสอบของคุณ ( 0-100 ): "))
#if score >= 50:: หมายความว่า "ถ้า" ตัวแปร score มีค่ามากกว่าหรือเท่ากับ (>=) 50 ให้ทำคำสั่งบรรทัดถัดไป
if score >=50:
    print("ยินดีด้วย! คุณสอบผ่าน")
else:
    print("เสียใจด้วย คุณสอบตกสู้ๆเด้อ")